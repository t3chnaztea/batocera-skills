#!/usr/bin/env python3
"""Generate SNES bezel/shader per-game overrides in batocera.conf.

Large-library fallback pattern: a bezel pack (thebezelproject here) has real game
art for only ~50 of ~760 SNES roms; everything else falls back to the pack's ugly
generic system bezel. Invert the defaults so the un-arted majority looks good:

  - system default: snes.bezel=none + a Koko-AIO ambilight shader frame
    (the clean look you'd use on handhelds / NES)
  - per-game overrides for roms WITH real art: bezel=thebezelproject + the
    period-accurate CRT-Royale S-Video shader
  - a special sub-group (SuperFX/3D titles) pinned to a different shader via
    EXACT-filename keys -- because configgen does exact gsname matching on the
    full rom filename incl. extension; glob keys like snes["Star Fox*"] never
    match and must be replaced with exact keys.

Idempotent: regenerates its own marker block, replaces the snes-renderer.shader
system line, removes any dead glob lines. Backs up batocera.conf first.

Adapt the paths (ROMS, ART, the shader constants, FX_PREFIXES) to your setup.
Run ON the Batocera box: python3 snes-bezel-fallback.py
"""
from pathlib import Path
import re
import time

CONF = Path("/userdata/system/batocera.conf")
ROMS = Path("/userdata/roms/snes")
ART = Path("/userdata/decorations/thebezelproject/games/snes")
KOKO = ("koko-aio-19-slang-presets-and-overlays/Duimon_additional_presets/"
        "presets_Monitor-Ambilight-immersive/logo_SNES")
ROYALE_SVIDEO = "presets/crt-plus-signal/crt-royale-ntsc-svideo"
SUPER_XBR = "crt/crt-super-xbr"
ROM_EXTS = {".sfc", ".smc", ".zip", ".7z", ".bin"}
# SuperFX/3D games pinned to super-xbr (prefix match). Replace with your own.
FX_PREFIXES = ("Star Fox", "Dirt Trax FX", "Stunt Race FX", "Vortex (USA)",
               "Doom (USA)", "Super Mario World 2 - Yoshi's Island")
BEGIN = "## BEGIN snes-bezel-fallback (generated by snes-bezel-fallback.py)"
END = "## END snes-bezel-fallback"

def gsname(filename: str) -> str:
    # configgen's FileData::getConfigurationName(): rom filename minus '=' and '#'
    return filename.replace("=", "").replace("#", "")

def main() -> None:
    roms = sorted(p for p in ROMS.iterdir()
                  if p.suffix.lower() in ROM_EXTS and p.is_file())
    art_stems = {p.stem for p in ART.glob("*.png")}

    block = [BEGIN]
    block.append("# system default: koko ambilight frame (no decoration)")
    block.append("snes.bezel=none")
    n_art = n_fx = 0
    for rom in roms:
        is_fx = rom.stem.startswith(FX_PREFIXES)
        has_art = rom.stem in art_stems
        if not (is_fx or has_art):
            continue  # system default covers it
        g = gsname(rom.name)
        if has_art:
            block.append(f'snes["{g}"].bezel=thebezelproject')
            n_art += 1
        if is_fx:
            block.append(f'snes["{g}"]-renderer.shader={SUPER_XBR}')
            n_fx += 1
        elif has_art:
            block.append(f'snes["{g}"]-renderer.shader={ROYALE_SVIDEO}')
    block.append(END)

    text = CONF.read_text(encoding="utf-8")
    # drop any previous generated block
    text = re.sub(rf"\n?{re.escape(BEGIN)}.*?{re.escape(END)}\n?", "\n",
                  text, flags=re.DOTALL)
    # system shader becomes the koko fallback
    text = re.sub(r"^snes-renderer\.shader=.*$",
                  f"snes-renderer.shader={KOKO}", text, flags=re.MULTILINE)
    # remove any dead glob lines
    text = re.sub(r'^snes\["[^"]*\*"\]-renderer\.shader=.*\n', "",
                  text, flags=re.MULTILINE)
    if not text.endswith("\n"):
        text += "\n"
    text += "\n".join(block) + "\n"

    bak = CONF.with_name(f"batocera.conf.bak-snesbezel-{time.strftime('%Y%m%d-%H%M%S')}")
    bak.write_bytes(CONF.read_bytes())
    CONF.write_text(text, encoding="utf-8")
    print(f"roms={len(roms)} with_tbp_art={n_art} fx_pinned={n_fx} "
          f"fallback_to_koko={len(roms) - n_art - n_fx}")
    print(f"backup: {bak}")

if __name__ == "__main__":
    main()
